-- Cached coordinates used by event dashboards. Only aggregated location
-- labels are stored here; participant identity is never sent for geocoding.
CREATE TABLE IF NOT EXISTS public.participant_location_geocodes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_key TEXT NOT NULL UNIQUE,
  city TEXT NOT NULL,
  neighborhood TEXT,
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  status TEXT NOT NULL DEFAULT 'resolved'
    CHECK (status IN ('resolved', 'not_found')),
  source TEXT NOT NULL DEFAULT 'nominatim',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (
    (status = 'resolved' AND latitude IS NOT NULL AND longitude IS NOT NULL)
    OR status = 'not_found'
  )
);

CREATE INDEX IF NOT EXISTS idx_participant_location_geocodes_city
ON public.participant_location_geocodes(city);

ALTER TABLE public.participant_location_geocodes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated users can read location geocodes"
ON public.participant_location_geocodes;
CREATE POLICY "Authenticated users can read location geocodes"
ON public.participant_location_geocodes FOR SELECT TO authenticated
USING (TRUE);

COMMENT ON TABLE public.participant_location_geocodes IS
  'Cache de coordenadas agregadas por cidade e bairro para dashboards de eventos.';
